import pandas as pd
from io import BytesIO
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side

router = APIRouter(prefix="/reports", tags=["Reports"])

# Teacher: Get full attendance report
@router.get("/teacher/attendance")
async def get_teacher_attendance_report(
    current_user: dict = Depends(get_current_user),
    class_id: str = None,
    start_date: str = None,
    end_date: str = None
):
    """Generate Excel attendance report for teacher"""
    
    if current_user["role"] != "teacher":
        raise HTTPException(status_code=403, detail="Teacher access required")
    
    db = get_database()
    
    # Build query
    query = {}
    if class_id:
        # Get students in this class
        students = await db.students.find({"class_id": class_id}).to_list(None)
        student_names = [s.get("name") for s in students]
        if student_names:
            query["student_name"] = {"$in": student_names}
    
    # Date filter
    if start_date and end_date:
        query["date"] = {"$gte": start_date, "$lte": end_date}
    elif start_date:
        query["date"] = {"$gte": start_date}
    elif end_date:
        query["date"] = {"$lte": end_date}
    
    # Get attendance records
    attendance = await db.attendance.find(query).to_list(None)
    
    # Create DataFrame
    data = []
    for a in attendance:
        data.append({
            "Student Name": a.get("student_name", ""),
            "Date": a.get("date", ""),
            "Time": a.get("time", ""),
            "Status": "Present",
            "Confidence (%)": round(a.get("confidence", 0) * 100, 1)
        })
    
    if not data:
        # Return empty report
        df = pd.DataFrame(columns=["Student Name", "Date", "Time", "Status", "Confidence (%)"])
    else:
        df = pd.DataFrame(data)
    
    # Create Excel file with styling
    output = BytesIO()
    with pd.ExcelWriter(output, engine='openpyxl') as writer:
        df.to_excel(writer, sheet_name='Attendance', index=False)
        
        # Get workbook and worksheet
        workbook = writer.book
        worksheet = writer.sheets['Attendance']
        
        # Add header styling
        header_font = Font(bold=True, color="FFFFFF")
        header_fill = PatternFill(start_color="4CAF50", end_color="4CAF50", fill_type="solid")
        header_alignment = Alignment(horizontal="center", vertical="center")
        
        for cell in worksheet[1]:
            cell.font = header_font
            cell.fill = header_fill
            cell.alignment = header_alignment
        
        # Adjust column widths
        for column in worksheet.columns:
            max_length = 0
            column_letter = column[0].column_letter
            for cell in column:
                try:
                    if len(str(cell.value)) > max_length:
                        max_length = len(str(cell.value))
                except:
                    pass
            adjusted_width = min(max_length + 2, 30)
            worksheet.column_dimensions[column_letter].width = adjusted_width
        
        # Add summary sheet
        summary_df = pd.DataFrame({
            "Report Info": ["Generated By", "Generated On", "Total Records", "Unique Students"],
            "Value": [
                current_user.get("full_name", "Teacher"),
                datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                len(data),
                len(set([a.get("student_name") for a in attendance]))
            ]
        })
        summary_df.to_excel(writer, sheet_name='Summary', index=False)
    
    output.seek(0)
    
    filename = f"attendance_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.xlsx"
    
    return StreamingResponse(
        output,
        media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        headers={"Content-Disposition": f"attachment; filename={filename}"}
    )

# Student: Get own attendance report
@router.get("/student/attendance")
async def get_student_attendance_report(current_user: dict = Depends(get_current_user)):
    """Generate Excel attendance report for student"""
    
    if current_user["role"] != "student":
        raise HTTPException(status_code=403, detail="Student access required")
    
    db = get_database()
    
    # Get student record
    student = await db.students.find_one({"user_id": str(current_user["_id"])})
    if not student:
        student = await db.students.find_one({"email": current_user["email"]})
    
    if not student:
        raise HTTPException(status_code=404, detail="Student record not found")
    
    # Get attendance records
    attendance = await db.attendance.find({"student_name": student.get("name")}).to_list(None)
    
    # Create DataFrame
    data = []
    for a in attendance:
        data.append({
            "Date": a.get("date", ""),
            "Time": a.get("time", ""),
            "Status": "Present",
            "Confidence (%)": round(a.get("confidence", 0) * 100, 1)
        })
    
    # Sort by date descending
    data.sort(key=lambda x: x["Date"], reverse=True)
    
    if not data:
        df = pd.DataFrame(columns=["Date", "Time", "Status", "Confidence (%)"])
    else:
        df = pd.DataFrame(data)
    
    # Calculate summary
    present_days = len(data)
    
    # Create Excel file
    output = BytesIO()
    with pd.ExcelWriter(output, engine='openpyxl') as writer:
        df.to_excel(writer, sheet_name='My Attendance', index=False)
        
        # Get workbook and worksheet
        workbook = writer.book
        worksheet = writer.sheets['My Attendance']
        
        # Add header styling
        header_font = Font(bold=True, color="FFFFFF")
        header_fill = PatternFill(start_color="2196F3", end_color="2196F3", fill_type="solid")
        
        for cell in worksheet[1]:
            cell.font = header_font
            cell.fill = header_fill
            cell.alignment = Alignment(horizontal="center", vertical="center")
        
        # Adjust column widths
        for column in worksheet.columns:
            max_length = 0
            column_letter = column[0].column_letter
            for cell in column:
                try:
                    if len(str(cell.value)) > max_length:
                        max_length = len(str(cell.value))
                except:
                    pass
            adjusted_width = min(max_length + 2, 25)
            worksheet.column_dimensions[column_letter].width = adjusted_width
        
        # Add summary sheet
        summary_df = pd.DataFrame({
            "Student Info": ["Student Name", "Roll Number", "Total Present Days", "Report Generated On"],
            "Value": [
                student.get("name", ""),
                student.get("roll_number", ""),
                present_days,
                datetime.now().strftime("%Y-%m-%d %H:%M:%S")
            ]
        })
        summary_df.to_excel(writer, sheet_name='Summary', index=False)
    
    output.seek(0)
    
    filename = f"my_attendance_{student.get('roll_number', 'student')}_{datetime.now().strftime('%Y%m%d')}.xlsx"
    
    return StreamingResponse(
        output,
        media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        headers={"Content-Disposition": f"attachment; filename={filename}"}
    )

# Teacher: Get class-wise summary report
@router.get("/teacher/summary")
async def get_class_summary(current_user: dict = Depends(get_current_user)):
    """Get summary statistics for teacher dashboard"""
    
    if current_user["role"] != "teacher":
        raise HTTPException(status_code=403, detail="Teacher access required")
    
    db = get_database()
    
    # Get all classes for this teacher
    classes = await db.classes.find({"teacher_id": str(current_user["_id"])}).to_list(None)
    
    result = []
    for cls in classes:
        # Get students in this class
        students = await db.students.find({"class_id": str(cls["_id"])}).to_list(None)
        student_names = [s.get("name") for s in students]
        
        # Get attendance records for these students
        attendance_count = await db.attendance.count_documents({
            "student_name": {"$in": student_names}
        }) if student_names else 0
        
        # Get unique dates for attendance
        unique_dates = await db.attendance.distinct("date", {
            "student_name": {"$in": student_names}
        }) if student_names else []
        
        result.append({
            "class_id": str(cls["_id"]),
            "class_name": cls.get("class_name", ""),
            "section": cls.get("section", ""),
            "subject": cls.get("subject", ""),
            "total_students": len(students),
            "total_attendance_records": attendance_count,
            "attendance_days": len(unique_dates)
        })
    
    return result